function [ u_k4, e1_4 ] = FISTA ( u0, Fu_star, iter2, L_f, lambda, ep )
disp(['FISTA L_f=', num2str(L_f), ' ...']);
tau=1/L_f;
mu=0;
mu_g=0.1;
mu_f=0;
%--------------------------------------------------------------------
x0=D_gradient( u0 );
x1=x0;
%--------------------------------------------------------------------
q=0;
t(1)=1;
%--------------------------------------------------------------------
%%
k=1;
t(k+1)=(1+sqrt(1+(4*(t(k)^2))))/2;
beta(k)=(t(k)-1)/t(k+1);
%--------------------------------------------------------------------
y=x1+(beta(k))*(x1-x0);
y_tilde=y-tau*grad_f(y,u0);
%--------------------------------------------------------------------
p=prox_tau_g( y_tilde,lambda,tau,mu_g );
x2=p;
F_AD=F_dual( p,u0,lambda,ep );
%--------------------------------------------------------------------
x0=x1;
x1=x2;
F_u4(k)=F_dual( x2,u0,lambda,ep );
%%
for k=2:iter2+1
    t(k+1)=(1+sqrt(1+(4*(t(k)^2))))/2;
    beta(k)=(t(k)-1)/t(k+1);
    y=x1+beta(k)*((x1-x0)+(t(k)/(t(k)-1))*(p-x1));
    y_tilde=y-tau*grad_f(y,u0);
    %-----------------------------------------------------------------
    p=prox_tau_g( y_tilde,lambda,tau,mu_g );
    %-----------------------------------------------------------------
    F_ad=F_dual( p,u0,lambda,ep );
    if ( F_ad<=F_AD )
        x2=p;
        F_AD=F_ad;
    else
        x2=x1;
        t(k+1)=1;
    end
    %-----------------------------------------------------------------
    F_u4(k)=F_dual( x2,u0,lambda,ep );
    x0=x1;
    x1=x2;
end
%%
u_k4=u0-D_adjoint( x2 );
%%
for i=1:(iter2+1);
    e1_4(i)=F_u4(i)-Fu_star;
end
end

